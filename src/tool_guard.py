"""
AgentGuard AI - Tool Execution Sandboxing & Schema Interceptor.
Guards autonomous AI agent tool calls against SQL injection,
destructive OS commands, reverse shells, and parameter bound violations.
"""

import re
from typing import Dict, Any, List, Optional


SQL_INJECTION_PATTERNS = [
    re.compile(r"(?i)\b(drop\s+table|drop\s+database|truncate\s+table|alter\s+table)\b"),
    re.compile(r"(?i)\bdelete\s+from\s+\w+\s*(where\s+1\s*=\s*1|;|\s*$)"),
    re.compile(r"(?i)\bunion\s+(all\s+)?select\b"),
    re.compile(r"(?i)(--|#|/\*).*\b(drop|exec|select|delete)\b"),
    re.compile(r"(?i)\bor\s+['\"]?1['\"]?\s*=\s*['\"]?1['\"]?"),
    re.compile(r"(?i)\bexec(ute)?\s*\(\s*['\"]"),
    re.compile(r"(?i)\bxp_cmdshell\b")
]

DANGEROUS_OS_PATTERNS = [
    re.compile(r"(?i)\brm\s+-r?f\s+[/~*]"),
    re.compile(r"(?i)\b(del|erase)\s+/[fsq]\b"),
    re.compile(r"(?i)\bformat\s+[a-z]:"),
    re.compile(r"(?i)\bmkfs(\.\w+)?\b"),
    re.compile(r"(?i)\bcurl\s+[^|]+\|\s*(ba)?sh\b"),
    re.compile(r"(?i)\bwget\s+[^|]+\|\s*(ba)?sh\b"),
    re.compile(r"(?i)\bpowershell\s+(-enc|-encodedcommand)\b"),
    re.compile(r"(?i)\b(nc|netcat)\s+.*-e\b"),
    re.compile(r"(?i)/etc/(passwd|shadow)")
]


class ToolCallGuard:
    """
    Enforces security policies on tool invocation requests generated by autonomous agents.
    """

    DEFAULT_ALLOWED_TOOLS = [
        "web_search",
        "calculator",
        "database_query",
        "send_email",
        "read_file",
        "crm_lookup"
    ]

    def __init__(self, allowed_tools: Optional[List[str]] = None):
        self.allowed_tools = set(allowed_tools or self.DEFAULT_ALLOWED_TOOLS)

    def validate_tool_call(
        self,
        tool_name: str,
        arguments: Dict[str, Any],
        strict_tool_whitelist: bool = True
    ) -> Dict[str, Any]:
        """
        Inspect tool execution payload for security policy violations.
        """
        violations: List[str] = []
        severity = "CLEAN"

        # 1. Whitelist Check
        if strict_tool_whitelist and tool_name not in self.allowed_tools:
            violations.append(f"Tool '{tool_name}' is not in authorized agent tool whitelist.")
            severity = "HIGH"

        # Inspect all string arguments for malicious injections
        for arg_key, arg_val in arguments.items():
            if isinstance(arg_val, str):
                # SQL Injection Analysis
                for pattern in SQL_INJECTION_PATTERNS:
                    if pattern.search(arg_val):
                        violations.append(
                            f"Argument '{arg_key}' contains prohibited SQL injection or destructive DDL pattern."
                        )
                        severity = "CRITICAL"
                        break

                # OS Command Injection Analysis
                for pattern in DANGEROUS_OS_PATTERNS:
                    if pattern.search(arg_val):
                        violations.append(
                            f"Argument '{arg_key}' contains dangerous system command or reverse shell pattern."
                        )
                        severity = "CRITICAL"
                        break

            # Parameter Bounds Check
            if arg_key in ["limit", "count", "top_k", "max_results"]:
                if isinstance(arg_val, (int, float)) and arg_val > 1000:
                    violations.append(
                        f"Parameter '{arg_key}' value ({arg_val}) exceeds maximum enterprise threshold (1000)."
                    )
                    if severity == "CLEAN":
                        severity = "MEDIUM"

        is_allowed = len(violations) == 0

        return {
            "is_safe": is_allowed,
            "tool_name": tool_name,
            "severity": severity,
            "action": "EXECUTE" if is_allowed else "BLOCK_EXECUTION",
            "violation_count": len(violations),
            "violations": violations
        }
